import { checkMatmul } from '../device.ts'
import type { ComputeDevice, DeviceBuffer, DeviceInfo, DeviceMemory, MatmulSpec } from '../device.ts'
import { CudaApi } from './driver.ts'
import { KERNEL_NAMES } from './ptx.ts'
import type { KernelName } from './ptx.ts'
import { type ProgramName, PROGRAMS, PROGRAM_NAMES } from './ops'
import { type KernelArgument } from './driver'
import { moduleSource } from './module'

const MAX_GRID_Z = 65535
const mib = (bytes: number): string => `${(bytes / 1_048_576).toFixed(0)} MiB`

/** A region of a buffer, starting `offset` elements in. */
export interface BufferSlice {
	readonly buffer: DeviceBuffer
	readonly offset: number
}

class CudaBuffer implements DeviceBuffer {
	readonly device = 'cuda' as const
	disposed = false

	constructor(readonly owner: CudaDevice, readonly pointer: bigint, readonly length: number) { }

	get byteLength(): number {
		return this.length * 4
	}
}

/**
 * A CUDA device driven through the driver API. Kernels are PTX generated by this package and compiled by the
 * driver when the device is created. Launches are asynchronous: call `synchronize()` (or download, which waits)
 * before trusting a result or a clock.
 */
export class CudaDevice implements ComputeDevice {
	readonly info: DeviceInfo
	readonly #api: CudaApi
	readonly #handle: number
	readonly #module: bigint
	readonly #functions: ReadonlyMap<string, bigint>
	readonly #live = new Map<bigint, number>()
	#allocated = 0
	#disposed = false

	private constructor(api: CudaApi, handle: number, module: bigint, functions: ReadonlyMap<string, bigint>, info: DeviceInfo) {
		this.#api = api
		this.#handle = handle
		this.#module = module
		this.#functions = functions
		this.info = info
	}

	/** Initialises the driver, retains the device's primary context and compiles the kernels. Throws on any failure. */
	static create(index = 0): CudaDevice {
		const api = CudaApi.load()
		const count = api.deviceCount()
		if (count === 0) throw new Error('The driver reports no CUDA devices')
		if (!Number.isInteger(index) || index < 0 || index >= count) throw new RangeError(`GPU ${index} does not exist; the driver reports ${count} device(s)`)
		const properties = api.properties(index)
		const handle = api.deviceHandle(index)
		const context = new BigUint64Array(1)
		api.check(api.symbols.cuDevicePrimaryCtxRetain(context, handle), 'cuDevicePrimaryCtxRetain')
		try {
			api.check(api.symbols.cuCtxSetCurrent(context[0]!), 'cuCtxSetCurrent')
			const module = api.loadModule(moduleSource())
			const names: string[] = [...KERNEL_NAMES, ...PROGRAM_NAMES]
			const functions = new Map<string, bigint>(names.map((name) => [name, api.getFunction(module, name)] as const))
			const info: DeviceInfo = {
				kind: 'cuda',
				name: properties.name,
				index,
				totalMemoryBytes: properties.totalMemoryBytes,
				precisions: ['f32'],
				computeCapability: properties.computeCapability,
				driverVersion: api.driverVersion,
				multiprocessors: properties.multiprocessors
			}
			return new CudaDevice(api, handle, module, functions, info)
		} catch (error) {
			api.symbols.cuDevicePrimaryCtxRelease_v2(handle)
			throw error
		}
	}

	alloc(length: number): DeviceBuffer {
		this.#alive()
		if (!Number.isInteger(length) || length < 0) throw new RangeError(`A buffer needs a non-negative integer length, received ${length}`)
		const bytes = Math.max(1, length) * 4
		const out = new BigUint64Array(1)
		const status = this.#api.symbols.cuMemAlloc_v2(out, BigInt(bytes))
		if (status === 2) {
			const memory = this.memory()
			throw new RangeError(`The GPU is out of memory: ${mib(bytes)} requested, ${mib(memory.freeBytes)} free of ${mib(memory.totalBytes)} (${mib(memory.allocatedBytes)} held by this process). Use a smaller model, batch or context.`)
		}
		this.#api.check(status, 'cuMemAlloc')
		this.#live.set(out[0]!, bytes)
		this.#allocated += bytes
		return new CudaBuffer(this, out[0]!, length)
	}

	free(buffer: DeviceBuffer): void {
		const own = this.#own(buffer)
		this.#api.check(this.#api.symbols.cuMemFree_v2(own.pointer), 'cuMemFree')
		this.#allocated -= this.#live.get(own.pointer) ?? 0
		this.#live.delete(own.pointer)
		own.disposed = true
	}

	upload(target: DeviceBuffer, source: Float32Array, targetOffset = 0): void {
		const own = this.#own(target)
		if (targetOffset < 0 || targetOffset + source.length > own.length) throw new RangeError('The upload does not fit in the buffer')
		if (source.length === 0) return
		this.#api.check(this.#api.symbols.cuMemcpyHtoD_v2(own.pointer + BigInt(targetOffset * 4), source, BigInt(source.byteLength)), 'cuMemcpyHtoD')
	}

	download(source: DeviceBuffer, target: Float32Array, sourceOffset = 0): void {
		const own = this.#own(source)
		if (sourceOffset < 0 || sourceOffset + target.length > own.length) throw new RangeError('The download reads past the end of the buffer')
		if (target.length === 0) return
		this.#api.check(this.#api.symbols.cuMemcpyDtoH_v2(target, own.pointer + BigInt(sourceOffset * 4), BigInt(target.byteLength)), 'cuMemcpyDtoH')
	}

	fill(target: DeviceBuffer, value: number): void {
		const own = this.#own(target)
		const bits = new Uint32Array(new Float32Array([value]).buffer)[0]!
		this.#api.check(this.#api.symbols.cuMemsetD32_v2(own.pointer, bits, BigInt(own.length)), 'cuMemsetD32')
	}

	add(a: DeviceBuffer, b: DeviceBuffer, out: DeviceBuffer): void {
		const [x, y, z] = [this.#own(a), this.#own(b), this.#own(out)]
		if (x.length !== y.length || x.length !== z.length) throw new RangeError('add needs buffers of equal length')
		this.#api.launch(this.#kernel('add_f32'), [Math.ceil(z.length / 256), 1, 1], [256, 1, 1], [{ type: 'u64', value: x.pointer }, { type: 'u64', value: y.pointer }, { type: 'u64', value: z.pointer }, { type: 'u32', value: z.length }])
	}

	scale(x: DeviceBuffer, out: DeviceBuffer, alpha: number): void {
		const [source, target] = [this.#own(x), this.#own(out)]
		if (source.length !== target.length) throw new RangeError('scale needs buffers of equal length')
		this.#api.launch(this.#kernel('scale_f32'), [Math.ceil(target.length / 256), 1, 1], [256, 1, 1], [{ type: 'u64', value: source.pointer }, { type: 'u64', value: target.pointer }, { type: 'u32', value: target.length }, { type: 'f32', value: alpha }])
	}

	matmul(a: DeviceBuffer, b: DeviceBuffer, c: DeviceBuffer, spec: MatmulSpec): void {
		const [left, right, out] = [this.#own(a), this.#own(b), this.#own(c)]
		if (out === left || out === right) throw new RangeError('The output of matmul must not alias an input')
		checkMatmul(spec, { a: left.length, b: right.length, c: out.length })
		const { m, k, n } = spec
		const name: KernelName = spec.transposeA ? (spec.transposeB ? 'sgemm_tt' : 'sgemm_tn') : spec.transposeB ? 'sgemm_nt' : 'sgemm_nn'
		const kernel = this.#kernel(name)
		const strides = [spec.transposeA ? 1 : k, spec.transposeA ? m : 1, spec.transposeB ? 1 : n, spec.transposeB ? k : 1] as const
		for (let first = 0; first < spec.batch; first += MAX_GRID_Z) {
			const count = Math.min(MAX_GRID_Z, spec.batch - first)
			const at = (pointer: bigint, offset: number | undefined, stride: number): bigint => pointer + BigInt(((offset ?? 0) + first * stride) * 4)
			this.#api.launch(kernel, [Math.ceil(n / 64), Math.ceil(m / 64), count], [256, 1, 1], [
				{ type: 'u64', value: at(left.pointer, spec.offsetA, spec.strideA) },
				{ type: 'u64', value: at(right.pointer, spec.offsetB, spec.strideB) },
				{ type: 'u64', value: at(out.pointer, spec.offsetC, spec.strideC) },
				{ type: 'u32', value: m }, { type: 'u32', value: n }, { type: 'u32', value: k },
				{ type: 's32', value: strides[0] }, { type: 's32', value: strides[1] }, { type: 's32', value: strides[2] }, { type: 's32', value: strides[3] },
				{ type: 's64', value: BigInt(spec.strideA) }, { type: 's64', value: BigInt(spec.strideB) }, { type: 's64', value: BigInt(spec.strideC) },
				{ type: 'f32', value: spec.alpha ?? 1 }, { type: 'f32', value: spec.beta ?? 0 }
			])
		}
	}

	synchronize(): void {
		this.#alive()
		this.#api.check(this.#api.symbols.cuCtxSynchronize(), 'cuCtxSynchronize')
	}

	measure(work: () => void): number {
		this.#alive()
		const { symbols } = this.#api
		const events = [new BigUint64Array(1), new BigUint64Array(1)] as const
		for (const event of events) this.#api.check(symbols.cuEventCreate(event, 0), 'cuEventCreate')
		try {
			this.#api.check(symbols.cuEventRecord(events[0][0]!, 0n), 'cuEventRecord')
			work()
			this.#api.check(symbols.cuEventRecord(events[1][0]!, 0n), 'cuEventRecord')
			this.#api.check(symbols.cuEventSynchronize(events[1][0]!), 'cuEventSynchronize')
			const elapsed = new Float32Array(1)
			this.#api.check(symbols.cuEventElapsedTime(elapsed, events[0][0]!, events[1][0]!), 'cuEventElapsedTime')
			return elapsed[0]!
		} finally {
			for (const event of events) symbols.cuEventDestroy_v2(event[0]!)
		}
	}

	memory(): DeviceMemory {
		this.#alive()
		const free = new BigUint64Array(1)
		const total = new BigUint64Array(1)
		this.#api.check(this.#api.symbols.cuMemGetInfo_v2(free, total), 'cuMemGetInfo')
		return { freeBytes: Number(free[0]!), totalBytes: Number(total[0]!), allocatedBytes: this.#allocated }
	}

	dispose(): void {
		if (this.#disposed) return
		this.#disposed = true
		for (const pointer of this.#live.keys()) this.#api.symbols.cuMemFree_v2(pointer)
		this.#live.clear()
		this.#allocated = 0
		this.#api.symbols.cuModuleUnload(this.#module)
		this.#api.symbols.cuDevicePrimaryCtxRelease_v2(this.#handle)
	}

	#alive(): void {
		if (this.#disposed) throw new Error('This device has been disposed')
	}

	#kernel(name: string): bigint {
		this.#alive()
		const kernel = this.#functions.get(name)
		if (kernel === undefined) throw new Error(`Kernel ${name} is not loaded`)
		return kernel
	}

	#own(buffer: DeviceBuffer): CudaBuffer {
		this.#alive()
		if (!(buffer instanceof CudaBuffer) || buffer.owner !== this) throw new TypeError('This buffer belongs to a different device')
		if (buffer.disposed) throw new Error('This buffer has been freed')
		return buffer
	}

	/**
	 * Launches a compiled neural-network program. Prefer the typed wrappers in `NeuralOps`, which also check
	 * that every buffer is large enough for the sizes passed.
	 */
	runProgram(name: ProgramName, grid: readonly [number, number, number], block: number, buffers: Readonly<Record<string, DeviceBuffer | BufferSlice>>, ints: Readonly<Record<string, number>>, floats: Readonly<Record<string, number>>): void {
		const program = PROGRAMS[name]
		const args: KernelArgument[] = []
		for (const bufferName of program.buffers) {
			const given = buffers[bufferName]
			if (given === undefined) throw new Error(`${name} needs a buffer named "${bufferName}"`)
			const slice: BufferSlice = 'buffer' in given ? given : { buffer: given, offset: 0 }
			args.push({ type: 'u64', value: this.#own(slice.buffer).pointer + BigInt(slice.offset * 4) })
		}
		for (const intName of program.ints) {
			const value = ints[intName]
			if (value === undefined) throw new Error(`${name} needs the integer "${intName}"`)
			args.push({ type: 'u32', value })
		}
		for (const floatName of program.floats) {
			const value = floats[floatName]
			if (value === undefined) throw new Error(`${name} needs the float "${floatName}"`)
			args.push({ type: 'f32', value })
		}
		this.#api.launch(this.#kernel(name), grid, [block, 1, 1], args)
	}
}
